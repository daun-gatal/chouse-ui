#!/usr/bin/env bash
# Starts the CHouse UI lab and prints how to sign in. Used by the Codespaces
# lab (devcontainer.json runs it on every start), by CI (lab.yml) and by
# anyone with Docker:
#
#   bash .devcontainer/lab/up.sh
#
# Safe to run again. On the first run it writes .env with random secrets and a
# random admin password (never the public defaults). Later runs reuse them.
#
# Environment:
#   CHOUSE_IMAGE       CHouse UI image to run (default ghcr.io/daun-gatal/chouse-ui:latest)
#   OPENAI_API_KEY / ANTHROPIC_API_KEY   optional; turns on AI with the visitor's own key
#   LAB_AI_MODEL       optional model override for that provider
#   LAB_URL            the address your browser uses, when it is not localhost or
#                      a codespace (for example a remote Docker host)
set -euo pipefail

LAB_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="$LAB_DIR/.env"
STATE_DIR="$LAB_DIR/.state"
PROJECT=chouse-lab
PORT=5521

compose() {
  docker compose --project-name "$PROJECT" -f "$LAB_DIR/compose.yml" --env-file "$ENV_FILE" "$@"
}

rand_hex() {
  head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'
}

lab_url() {
  if [ -n "${LAB_URL:-}" ]; then
    echo "${LAB_URL%/}"
  elif [ -n "${CODESPACE_NAME:-}" ]; then
    echo "https://${CODESPACE_NAME}-${PORT}.${GITHUB_CODESPACES_PORT_FORWARDING_DOMAIN:-app.github.dev}"
  else
    echo "http://localhost:${PORT}"
  fi
}

if ! docker info >/dev/null 2>&1; then
  echo "Docker is not running. In a codespace it starts with the container; wait a moment and run this script again." >&2
  exit 1
fi

mkdir -p "$STATE_DIR"

if [ ! -f "$ENV_FILE" ]; then
  # Data encrypted with lost secrets can't be read, so a leftover lab without
  # its .env is removed before starting fresh.
  if [ -n "$(docker volume ls -q --filter "label=com.docker.compose.project=$PROJECT")" ]; then
    echo "Removing an earlier lab whose secrets are gone..."
    docker ps -aq --filter "label=com.docker.compose.project=$PROJECT" | xargs -r docker rm -f >/dev/null
    docker volume ls -q --filter "label=com.docker.compose.project=$PROJECT" | xargs -r docker volume rm >/dev/null
  fi
  (
    umask 077
    {
      echo "# Generated by up.sh for this lab only. Never commit it."
      echo "JWT_SECRET=$(rand_hex 48)"
      echo "RBAC_ENCRYPTION_KEY=$(rand_hex 32)"
      echo "RBAC_ENCRYPTION_SALT=$(rand_hex 32)"
      # Upper, lower, digit and symbol, so it also meets the in-app password rules.
      echo "LAB_ADMIN_PASSWORD=Lab-$(rand_hex 8)-Ch1!"
      echo "CLICKHOUSE_PASSWORD=$(rand_hex 16)"
    } >"$ENV_FILE"
  )
fi

# The browser reaches the lab through the codespace's forwarded URL, or
# through localhost (VS Code desktop, local Docker). Allow exactly those.
ORIGINS="$(lab_url),http://localhost:${PORT},http://127.0.0.1:${PORT}"
if grep -q '^CORS_ORIGIN=' "$ENV_FILE"; then
  sed -i.bak "s#^CORS_ORIGIN=.*#CORS_ORIGIN=${ORIGINS}#" "$ENV_FILE" && rm -f "$ENV_FILE.bak"
else
  echo "CORS_ORIGIN=${ORIGINS}" >>"$ENV_FILE"
fi

echo "Starting CHouse UI and ClickHouse (the first start pulls the images)..."
compose up -d --wait --wait-timeout 300 chouse-ui clickhouse

echo "Loading sample data..."
seed_status=0
compose run --rm -T seed >"$STATE_DIR/seed.json" || seed_status=$?

compose up -d load

PASSWORD="$(grep '^LAB_ADMIN_PASSWORD=' "$ENV_FILE" | cut -d= -f2-)"
URL="$(lab_url)"
if grep -q '"ai":"on"' "$STATE_DIR/seed.json" 2>/dev/null; then
  AI_LINE="on, with your own key"
elif grep -q '"ai":"failed"' "$STATE_DIR/seed.json" 2>/dev/null; then
  AI_LINE="key found but setup failed; see the AI step above, or add a model under Admin > AI models"
else
  AI_LINE="off. Add an OPENAI_API_KEY or ANTHROPIC_API_KEY Codespaces secret and rebuild to turn it on"
fi

rm -f "$STATE_DIR/login.txt"
(
  umask 077
  printf 'URL=%s\nUSERNAME=admin\nPASSWORD=%s\n' "$URL" "$PASSWORD" >"$STATE_DIR/login.txt"
)

# The banner holds the password, so it is private like login.txt. Remove
# first: an existing file keeps its old mode.
rm -f "$STATE_DIR/banner.txt"
umask 077
{
  echo
  if [ "$seed_status" -eq 0 ]; then
    echo "CHouse UI lab is ready."
  else
    echo "CHouse UI lab started, but setting it up failed (see the FAIL lines above)."
    echo "  Retry:    bash .devcontainer/lab/up.sh"
    echo "  Report:   https://github.com/daun-gatal/chouse-ui/issues/new?labels=lab"
  fi
  echo "  Open:     $URL"
  echo "            (or the Ports tab > CHouse UI > globe icon)"
  echo "  Sign in:  admin / $PASSWORD"
  echo "            teammates maya (analyst), devon (developer) and vic (viewer) use the same password"
  echo "  AI:       $AI_LINE"
  echo "  Guide:    .devcontainer/lab/WELCOME.md"
  echo "  Done?     Delete the codespace at https://github.com/codespaces"
  echo
} | tee "$STATE_DIR/banner.txt"

exit "$seed_status"
